const fs = require('node:fs');
const ts = require('typescript');
const assert = require('node:assert/strict');
const source = ts.transpileModule(fs.readFileSync('src/lib/collections.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const moduleValue = {exports:{}};
new Function('exports','module',source)(moduleValue.exports,moduleValue);
const {selectCollectionWorks:select,parseCollection:parse,DEMO_COLLECTION:demo,collectionPath} = moduleValue.exports;
const works=[{id:'a',tags:['Dark',' trap ']},{id:'b',tags:['dark']},{id:'c',tags:['melodic']}];
const ids = value => value.map(work=>work.id);
assert.deepEqual(ids(select({work_ids:['c','a','missing','c'],tags:[' DARK '],tag_mode:'any'},works)),['c','a','b']);
assert.deepEqual(ids(select({work_ids:[],tags:['dark','trap'],tag_mode:'all'},works)),['a']);
assert.deepEqual(ids(select({work_ids:[],tags:[],tag_mode:'all'},works)),[]);
assert.deepEqual(ids(select({work_ids:['missing'],tags:['trap','melodic'],tag_mode:'any'},works)),['a','c']);
assert.equal(collectionPath(' Fimiquerro '),'/beats/send/fimiquerro');
assert.equal(parse({...demo,slug:'../admin'}),null);
assert.equal(parse({...demo,published:'true'}),null);
assert.equal(parse({...demo,artist:' '}),null);
assert.equal(parse({...demo,work_ids:Array(201).fill('a')}),null);
assert.deepEqual(parse({...demo,tags:[' Trap ','trap'],work_ids:['a','a']}).tags,['trap']);
assert.deepEqual(parse({...demo,work_ids:['a','a']}).work_ids,['a']);
console.log('Collection selection and validation checks passed');
