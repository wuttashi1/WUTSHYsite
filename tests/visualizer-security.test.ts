import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('Migration: ordinary signup cannot access settings, grant access or become admin; changes are audited',async()=>{
 const pg=new PGlite();
 await pg.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS; CREATE SCHEMA auth; CREATE SCHEMA storage;
 CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,email_confirmed_at timestamptz);
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 GRANT USAGE ON SCHEMA auth,public,storage TO anon,authenticated,service_role;
 INSERT INTO auth.users VALUES('11111111-1111-1111-1111-111111111111','den.velikiy562381@gmail.com',now());
 CREATE TABLE public.wutshy_settings(key text PRIMARY KEY,value jsonb);
 ALTER TABLE public.wutshy_settings ENABLE ROW LEVEL SECURITY;
 CREATE POLICY old_read ON public.wutshy_settings FOR SELECT USING(true);
 CREATE POLICY old_write ON public.wutshy_settings FOR ALL TO authenticated USING(true) WITH CHECK(true);
 INSERT INTO public.wutshy_settings VALUES('telegram','{"bot_token":"secret-fixture"}'),('hero','{}');
 CREATE TABLE storage.objects(id uuid,bucket_id text);
 ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
 CREATE POLICY old_storage ON storage.objects FOR ALL TO authenticated USING(true) WITH CHECK(true);
 GRANT ALL ON public.wutshy_settings,storage.objects TO authenticated;
 `);
 await pg.exec(await readFile('supabase/migrations/20261009_visualizer.sql','utf8'));
 await pg.exec(`GRANT SELECT ON public.visualizer_access,public.visualizer_admins TO authenticated; GRANT ALL ON public.visualizer_access,public.visualizer_presets TO authenticated,service_role;
 INSERT INTO auth.users VALUES('22222222-2222-2222-2222-222222222222','visitor@example.com',now());
 SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub','22222222-2222-2222-2222-222222222222',false);`);
 assert.equal((await pg.query<{is_site_admin:boolean}>('SELECT public.is_site_admin()')).rows[0].is_site_admin,false);
 assert.equal((await pg.query('SELECT * FROM public.visualizer_access')).rows.length,1);
 assert.equal((await pg.query<{access_status:string}>('SELECT access_status FROM public.visualizer_access')).rows[0].access_status,'PENDING');
 assert.equal((await pg.query('SELECT * FROM public.wutshy_settings')).rows.length,1);
 await assert.rejects(pg.exec("INSERT INTO public.wutshy_settings VALUES('attack','{}')"));
 await assert.rejects(pg.exec("INSERT INTO public.visualizer_admins VALUES('22222222-2222-2222-2222-222222222222')"));
 await pg.exec("UPDATE public.visualizer_access SET access_status='ACTIVE',access_start=now(),access_type='PERMANENT'");
 assert.equal((await pg.query<{access_status:string}>('SELECT access_status FROM public.visualizer_access')).rows[0].access_status,'PENDING');
 await pg.exec(`RESET ROLE; SELECT set_config('request.headers','{"x-admin-id":"11111111-1111-1111-1111-111111111111"}',false);
 UPDATE public.visualizer_access SET access_status='ACTIVE',access_start=now(),access_type='PERMANENT' WHERE user_id='22222222-2222-2222-2222-222222222222';`);
 const audit=await pg.query<{actor:string}>('SELECT actor FROM public.visualizer_audit ORDER BY id DESC LIMIT 1');assert.equal(audit.rows[0].actor,'11111111-1111-1111-1111-111111111111');
 await pg.exec("SELECT public.save_visualizer_preset(NULL,'One','{}',true,false,true); SELECT public.save_visualizer_preset(NULL,'Two','{}',true,false,true);");
 assert.equal((await pg.query('SELECT * FROM public.visualizer_presets WHERE is_default')).rows.length,1);
 await pg.close();
});
